/// <summary>
/// Как понимать вектор перемещения у <see cref="DoTweenMovementMonoBehaviour"/>.
/// </summary>
/// <remarks>
/// Вектор один, а значить он может разное: «поднять на метр над собой» и «улететь
/// в точку (0, 1, 0)» записываются одинаково. Раньше выбора не было — вектор всегда
/// читался как точка в мире, и объект, которому хотели задать покачивание, уезжал
/// в центр карты.
/// </remarks>
public enum DoTweenMovementSpace
{
    /// <summary>
    /// Смещение от собственной позиции объекта.
    /// </summary>
    /// <remarks>
    /// То, что нужно покачиванию и подскокам: с <c>Yoyo</c> объект ходит между своим
    /// местом и местом плюс вектор, где бы его ни поставили.
    /// </remarks>
    Offset = 0,

    /// <summary>
    /// Точка в координатах родителя.
    /// </summary>
    /// <remarks>
    /// Для объекта, который должен приехать в заданное место внутри своей иерархии —
    /// предмет в руке, створка в механизме.
    /// </remarks>
    Local = 1,

    /// <summary>
    /// Точка в мировых координатах.
    /// </summary>
    /// <remarks>
    /// Прежнее поведение компонента. Годится там, где цель и правда задана в мире
    /// и не зависит от того, куда попал сам объект.
    /// </remarks>
    World = 2,
}
