/// <summary>
/// Источник данных об уроне.
/// <para>
/// Реализуют как конкретные виды урона (<see cref="DamageBase"/> и наследники),
/// так и декораторы: каждый оборачивает предыдущий провайдер и возвращает изменённую
/// копию данных. Благодаря этому зональный множитель, критический флаг и прочие
/// поправки складываются цепочкой, не зная друг о друге.
/// </para>
/// </summary>
public interface IDamageProvider
{
    /// <summary>
    /// Данные урона на момент вызова. Декораторы возвращают копию, а не изменяют
    /// данные исходного провайдера, поэтому один провайдер можно использовать повторно.
    /// </summary>
    DamageData GetDamageData();
}
