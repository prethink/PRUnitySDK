/// <summary>
/// Чем закончилась попытка нанести урон.
/// </summary>
public enum DamageResult
{
    /// <summary>
    /// Урон не обработан: цель не умеет его принимать, данные не переданы
    /// или обработка прервана до расчёта.
    /// </summary>
    NotHandled,

    /// <summary>
    /// Атака не достигла цели. Отличается от <see cref="Blocked"/> тем, что
    /// попадания не было вовсе - на это состояние вешают эффект промаха.
    /// </summary>
    Miss,

    /// <summary>
    /// Попадание состоялось, но урон не прошёл: щит, неуязвимость или запрет
    /// от обработчика хука.
    /// </summary>
    Blocked,

    /// <summary>
    /// Урон нанесён, цель осталась жива.
    /// </summary>
    Damaged,

    /// <summary>
    /// Урон нанесён и оказался смертельным.
    /// </summary>
    Killed
}
