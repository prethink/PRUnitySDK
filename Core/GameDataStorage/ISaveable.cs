/// <summary>
/// Объект, чьё состояние живёт в сцене и попадает в сохранение по запросу.
/// </summary>
/// <remarks>
/// Нужен там, где состояние по природе принадлежит объекту и меняется часто: брейнрот
/// на холдере и накопленные им деньги. Данные, которые и так лежат в <c>ProjectData</c> —
/// кошелёк, открытые предметы, выбранная внешность, — пишутся туда сразу, и этот
/// интерфейс им не нужен.
/// <para>
/// Сбор синхронный: снимок должен получиться согласованным, а между ожиданиями состояние
/// успело бы измениться. Это запись в память, а не на диск, — долгой работе здесь не место.
/// </para>
/// </remarks>
public interface ISaveable
{
    /// <summary>
    /// Переносит состояние объекта в данные проекта.
    /// </summary>
    /// <returns><see langword="false"/>, если состояние отдать не удалось.</returns>
    bool TrySaveData();
}
