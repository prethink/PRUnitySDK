/// <summary>
/// Чем закончилось чтение сохранения.
/// </summary>
internal enum SaveReadResult
{
    /// <summary>
    /// Строка сохранения есть, но не прочиталась: не JSON, чужой ключ шифрования, несовместимые данные.
    /// </summary>
    /// <remarks>
    /// Хранилище после такого чтения не пишет: запись заменила бы сохранение игрока пустым.
    /// </remarks>
    Failed = 0,

    /// <summary>
    /// Сохранение прочитано и, если версия была старой, преобразовано.
    /// </summary>
    Loaded = 1,

    /// <summary>
    /// Сохранение отброшено из-за версии, вместо него создано новое.
    /// </summary>
    Discarded = 2,

    /// <summary>
    /// Строки сохранения нет: игрок запускает игру впервые.
    /// </summary>
    NotFound = 3
}
