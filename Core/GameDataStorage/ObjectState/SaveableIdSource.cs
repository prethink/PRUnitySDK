/// <summary>
/// Откуда берётся ключ, под которым состояние объекта лежит в сохранении.
/// </summary>
/// <remarks>
/// Ключ обязан быть одним и тем же при каждом запуске игры, иначе сохранённое состояние
/// не найдётся и объект каждый раз будет вставать в значения по умолчанию. Поэтому
/// <c>GetInstanceID()</c> в этом списке нет: Unity выдаёт его заново при каждой загрузке
/// сцены, и он годится только для сравнений внутри одного запуска.
/// </remarks>
public enum SaveableIdSource
{
    /// <summary>
    /// Собственный идентификатор компонента.
    /// </summary>
    /// <remarks>
    /// Генерируется один раз в редакторе и хранится в самом компоненте, поэтому едет
    /// вместе с префабом или сценой и переживает и перезапуск, и переименование объекта.
    /// Надёжнее прочих, и потому стоит по умолчанию.
    /// </remarks>
    OwnId = 0,

    /// <summary>
    /// Идентификатор цели: с неё берётся <see cref="IIdentifiable.Id"/>.
    /// </summary>
    /// <remarks>
    /// Для объектов, которые уже опознаны в игре, — например держателя с заданным
    /// в инспекторе <c>Id</c>. Состояние тогда одно на всех, у кого этот идентификатор
    /// совпадает, поэтому для нескольких одинаковых объектов не годится.
    /// </remarks>
    TargetId = 1
}
