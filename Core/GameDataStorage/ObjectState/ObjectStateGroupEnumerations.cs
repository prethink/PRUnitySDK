/// <summary>
/// Группы объектов, чьё состояние считают вместе.
/// </summary>
/// <remarks>
/// Пустой набор: своих групп у SDK нет, их заводит игра — partial-частью этого класса,
/// как и остальные наборы <c>Enumeration</c>. Группа нужна затем, что «сколько всего»
/// на уровне без неё складывает кристаллы, двери и купленные постройки в одно число,
/// из которого прогресс не собрать.
/// <para>
/// Сущностям своя группа обычно не нужна: у них уже есть <c>EntityType</c>, и он
/// подставляется сам, когда поле не заполнено. Этот набор — для объектов, которые
/// сущностями не являются, и для случаев, когда объекты одного типа считают порознь.
/// </para>
/// </remarks>
public partial class ObjectStateGroupEnumerations : EnumerationProviderBase
{
    /// <summary>
    /// Обычная группа: сюда попадает всё, чему не назначили свою.
    /// </summary>
    public static Enumeration Common = new Enumeration(nameof(Common));

    /// <inheritdoc />
    /// <remarks>
    /// Без этого объявления незаполненное поле остаётся пустым: набор знает своё
    /// «обычное» значение, а ссылка — нет, и подставить ей нечего.
    /// </remarks>
    public override Enumeration Default => Common;

    public override bool IncludeInherited => true;
}
