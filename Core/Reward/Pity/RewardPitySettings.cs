using System;
using UnityEngine;

/// <summary>
/// Гарант редкой награды: шанс редкого растёт с каждой прокруткой без него и в конце становится стопроцентным.
/// </summary>
/// <remarks>
/// Чистый случай при десятках попыток подряд даёт длинные пустые серии: игрок крутит двадцать раз
/// и не видит ничего стоящего. Гарант такую серию обрывает и делает ожидание видимым — «редкий
/// приз через три прокрутки» держит интерес лучше, чем «может быть, повезёт».
/// <para>
/// Свой у каждого розыгрыша: у колеса удачи и у каждого кейса отдельные настройки и отдельный
/// счётчик. Выключенный гарант розыгрыш не меняет вовсе.
/// </para>
/// </remarks>
[Serializable]
public sealed class RewardPitySettings
{
    [field: SerializeField]
    [field: Tooltip("Гарант включён. Выключен — награды разыгрываются только по весам, счётчик не ведётся.")]
    public bool Enabled { get; private set; }

    [field: SerializeField]
    [field: Tooltip("Награда этого качества и выше считается редкой: её шанс растёт, она же сбрасывает счётчик.")]
    public QualityType RareQuality { get; private set; } = QualityType.Epic;

    [SerializeField, Min(2)]
    [Tooltip("На какой по счёту прокрутке без редкой награды она гарантирована. 10 — девять неудач подряд, десятая точно редкая.")]
    private int guaranteeAfter = 10;

    [SerializeField, Min(0f)]
    [Tooltip("На сколько вырастает вес редких наград за каждую прокрутку без них: 0.25 — после четырёх неудач редкое выпадает вдвое чаще. Ноль — шанс не растёт, работает только гарантия.")]
    private float chanceGrowth = 0.25f;

    /// <summary>
    /// На какой по счёту прокрутке без редкой награды она гарантирована.
    /// </summary>
    public int GuaranteeAfter => Mathf.Max(2, guaranteeAfter);

    /// <summary>
    /// Прибавка к весу редких наград за каждую прокрутку без них, в долях исходного веса.
    /// </summary>
    public float ChanceGrowth => Mathf.Max(0f, chanceGrowth);
}
