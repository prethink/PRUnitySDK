/// <summary>
/// Условие: отвечает на вопрос, не меняя ничего вокруг.
/// </summary>
/// <remarks>
/// Отдельно от <c>IAction</c> намеренно. Действие совершает поступок, условие только
/// спрашивает, и у <c>IAction</c> уже есть свой <c>CanExecute()</c>: сядь условия
/// на тот же интерфейс, выпадашка <see cref="ReferenceSelectorAttribute"/> в слоте
/// условия начала бы предлагать действия — а выбранное там начисление ресурса
/// срабатывало бы прямо при проверке.
/// <para>
/// Условия хранят двумя способами, как и действия: ассетом (<see cref="ConditionBase"/>),
/// когда одна и та же настройка нужна в разных местах, и встроенным объектом
/// в инспекторе владельца, когда она уникальна:
/// <code>[SerializeReference, ReferenceSelector] private ICondition condition;</code>
/// </para>
/// </remarks>
public interface ICondition
{
    /// <summary>
    /// Выполнено ли условие сейчас.
    /// </summary>
    /// <remarks>
    /// Спрашивается часто — на каждый удар, на каждый кадр, — поэтому ответ обязан быть
    /// дешёвым и не менять состояние игры. Условие, которое что-то делает по дороге,
    /// ломает всех, кто спрашивает его «просто посмотреть».
    /// </remarks>
    bool Evaluate();
}
