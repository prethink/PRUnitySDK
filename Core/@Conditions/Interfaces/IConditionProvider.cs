/// <summary>
/// Объект, который держит условие и отдаёт его наружу.
/// </summary>
/// <remarks>
/// Нужен тем, кто показывает условие игроку: подпись над целью спрашивает правило
/// у компонента, не зная, что это за компонент. Сам владелец при этом остаётся собой -
/// <c>BlockDamageHook</c> решает, пропускать ли урон, а не рисует интерфейс.
/// <para>
/// Отдавать <c>null</c> законно: слот условия могли не заполнить, и это значит
/// «правила нет», а не ошибку.
/// </para>
/// </remarks>
public interface IConditionProvider
{
    /// <summary>
    /// Условие владельца либо <c>null</c>, если оно не задано.
    /// </summary>
    ICondition Condition { get; }
}
