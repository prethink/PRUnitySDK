using UnityEngine;

/// <summary>
/// Обстоятельства проверки условия: для кого и при каких данных спрашивают.
/// </summary>
/// <remarks>
/// Отдельный класс, а не список параметров у <see cref="ICondition.Evaluate(ConditionContextBase)"/>:
/// потребителям нужны разные данные — хуку урона атакующий и оружие, триггеру инициатор.
/// Параметр в сигнатуре пришлось бы добавлять во все реализации разом, а наследник
/// контекста добавляется, никого не трогая.
/// <para>
/// Условие, которому нужны особые данные, приводит контекст к своему типу. Не тот тип —
/// это не ошибка, а «данных нет»: такое условие отвечает так же, как на пустой слот.
/// </para>
/// <para>
/// Без обстоятельств спрашивают с <see cref="ConditionContextEmpty"/>.
/// </para>
/// </remarks>
public abstract class ConditionContextBase
{
    /// <summary>
    /// Тот, для кого проверяют условие; <c>null</c> для правил состояния мира.
    /// </summary>
    /// <remarks>
    /// Лежит в основе, а не в наследнике: «кто спрашивает» нужно почти любому контексту,
    /// и правило про участника не должно знать, откуда пришла проверка — от удара или
    /// от кнопки.
    /// </remarks>
    public virtual GameObject Actor => null;
}
