public interface IIdentifiable
{
    /// <summary>
    /// Идентификатор.
    /// </summary>
    /// <remarks>
    /// Произвольная строка, а не обязательно GUID. Предметы каталогов получают
    /// сгенерированный GUID, но ресурс возвращает ключ своего <c>Enumeration</c>
    /// (<c>Coin</c>, <c>Yan</c>), а проектный тип может задать идентификатор как угодно.
    /// Сравнивать значения можно только как строки: разбор через <c>Guid.Parse</c>
    /// отсечёт всё, кроме одного вида идентификаторов.
    /// </remarks>
    string Id { get; }
}
