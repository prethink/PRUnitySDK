/// <summary>
/// Дополнительный блок, который окно `Database` рисует под инспектором выбранного ассета.
/// </summary>
/// <remarks>
/// Точка расширения для модулей: публичное окно не знает про магазин, витрину или другие
/// проектные надстройки, но позволяет им показать свои настройки рядом с предметом.
/// Так всё настраивается в одном месте, хотя данные лежат в разных ассетах.
/// <para>
/// Реализации находятся автоматически через <c>TypeCache</c> — регистрировать их нигде
/// не нужно. Достаточно наследника с конструктором без параметров в любой Editor-сборке.
/// </para>
/// </remarks>
public interface IDatabaseAssetInspector
{
    /// <summary>
    /// Порядок отрисовки: меньшее значение — выше.
    /// </summary>
    int Order { get; }

    /// <summary>
    /// Блок относится к этому ассету.
    /// </summary>
    bool CanDraw(UnityEngine.Object asset);

    /// <summary>
    /// Рисует блок.
    /// </summary>
    /// <remarks>
    /// Вызывается внутри панели свойств, под обычным инспектором ассета.
    /// </remarks>
    void Draw(UnityEngine.Object asset);
}
