/// <summary>
/// Вкладка окна отладки для отдельной игры проекта: свои кнопки и состояние режима.
/// </summary>
/// <remarks>
/// Та же вкладка модуля (<see cref="IPRDebugTab"/>), но окно ставит такие вкладки в самый низ
/// списка, под разделителем: общие разделы SDK сверху, игры проекта — отдельно. Видна только вкладка
/// активного проекта (<see cref="Project"/>): игр много, и список не должен расти с каждой. Если её
/// игра сейчас не запущена, вкладка сама пишет об этом, а не прячется, — иначе список менялся бы на
/// ходу и выбранная вкладка съезжала.
/// </remarks>
public interface IPRDebugGameTab : IPRDebugTab
{
    /// <summary>
    /// Название проекта SDK (<see cref="PRSDKProject.Title"/>), при активном которой вкладка видна.
    /// Пусто — видна при любом проекте.
    /// </summary>
    string Project { get; }
}
