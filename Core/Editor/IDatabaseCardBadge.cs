using UnityEngine;

/// <summary>
/// Метка на карточке каталога: короткий признак, видный прямо в сетке.
/// </summary>
/// <remarks>
/// Точка расширения для модулей. Окно `Database` не знает ни про магазин, ни про другие
/// надстройки, но даёт им место на карточке — чтобы состояние читалось без выбора предмета
/// и без перехода в другую секцию.
/// <para>
/// Реализации находятся автоматически через <c>TypeCache</c>; достаточно наследника
/// с конструктором без параметров в любой Editor-сборке.
/// </para>
/// </remarks>
public interface IDatabaseCardBadge
{
    /// <summary>
    /// Порядок отрисовки: меньшее значение — левее.
    /// </summary>
    int Order { get; }

    /// <summary>
    /// Метка относится к этому ассету.
    /// </summary>
    bool CanDraw(Object asset);

    /// <summary>
    /// Ширина метки в пикселях.
    /// </summary>
    /// <remarks>
    /// Карточка узкая, и место делится между метками: просите столько, сколько нужно
    /// на самом деле.
    /// </remarks>
    float GetWidth(Object asset);

    /// <summary>
    /// Рисует метку в отведённой полосе внизу карточки.
    /// </summary>
    void Draw(Rect area, Object asset);
}
