/// <summary>
/// Способ показать игру как на телефоне ради снимка.
/// </summary>
/// <remarks>
/// Инструмент снимков лежит в ядре и не знает, из чего в игре собран мобильный вид.
/// Реализацию кладут рядом с тем, что она показывает, в папку <c>Editor</c>: инструмент
/// находит её сам, по типу, и зовёт вокруг «мобильных» кадров серии.
/// <para>
/// Вид включается на несколько секунд посреди идущей игры, поэтому реализация меняет
/// только то, что видно на экране, и возвращает всё как было.
/// </para>
/// </remarks>
public interface IPRScreenshotMobileMode
{
    /// <summary>
    /// Показать мобильный вид.
    /// </summary>
    void Enter();

    /// <summary>
    /// Вернуть вид, который был до <see cref="Enter"/>.
    /// </summary>
    void Exit();
}
