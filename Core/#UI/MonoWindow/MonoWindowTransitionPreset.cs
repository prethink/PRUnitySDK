/// <summary>
/// Готовый переход окна.
/// </summary>
/// <remarks>
/// Значения явные: номер хранится в настройках и префабах, новый пресет дописывается
/// в конец, а не вставляется между.
/// </remarks>
public enum MonoWindowTransitionPreset
{
    /// <summary>
    /// Выпрыгивает из центра с лёгким перелётом и сжимается обратно.
    /// </summary>
    Pop = 0,

    /// <summary>
    /// Мягко проявляется, чуть подрастая.
    /// </summary>
    Soft = 1,

    /// <summary>
    /// Только проявляется и гаснет, размер не меняется.
    /// </summary>
    Fade = 2,

    /// <summary>
    /// Въезжает снизу вверх и уезжает вниз.
    /// </summary>
    SlideUp = 3,

    /// <summary>
    /// Въезжает сверху вниз и уезжает вверх.
    /// </summary>
    SlideDown = 4,

    /// <summary>
    /// Пружинит, выскакивая из центра.
    /// </summary>
    Elastic = 5,

    /// <summary>
    /// Свои значения из поля <c>Custom</c>.
    /// </summary>
    Custom = 100,
}
