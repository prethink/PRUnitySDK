/// <summary>
/// Самостоятельный блок постоянного интерфейса: шапка, полоса опыта, панель кнопок.
/// </summary>
/// <remarks>
/// <see cref="IHudElement"/> прячет интерфейс целиком, канвасами. Блок прячется по одному —
/// так собирают кадр для снимка: убрать подсказку обучения и кнопки, оставить полосу опыта.
/// <para>
/// Скрытие здесь отладочное. Блок продолжает жить и обновляться, он лишь не рисуется, и
/// собственная логика блока — показать себя на шаге обучения, спрятать при открытом окне —
/// это состояние не отменяет.
/// </para>
/// </remarks>
public interface IHudBlock
{
    /// <summary>
    /// Название блока для списка в окне отладки.
    /// </summary>
    string BlockName { get; }

    /// <summary>
    /// Блок сейчас создан: есть что прятать.
    /// </summary>
    bool HasBlockView { get; }

    /// <summary>
    /// Блок спрятан отладкой.
    /// </summary>
    bool IsBlockHidden { get; }

    /// <summary>
    /// Прячет или возвращает блок.
    /// </summary>
    /// <remarks>
    /// Состояние запоминается и до появления блока: спрятанный заранее блок появится уже спрятанным.
    /// </remarks>
    void SetBlockHidden(bool hidden);
}
