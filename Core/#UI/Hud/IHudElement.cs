/// <summary>
/// Элемент постоянного интерфейса: полоса, панель, подпись над сущностью.
/// </summary>
/// <remarks>
/// Такие элементы приходят из разных мест и живут на разных canvas — экранном и мировых
/// над сущностями, — поэтому одним выключателем их не достать. Элемент регистрируется
/// в <see cref="HudTracker"/> и получает состояние от него, в том числе при появлении.
/// </remarks>
public interface IHudElement
{
    /// <summary>
    /// Показывает либо прячет элемент.
    /// </summary>
    /// <param name="isVisible">Элемент показан.</param>
    void SetHudVisible(bool isVisible);
}
