using System;

/// <summary>
/// Помечает фоновую задачу для автоматической регистрации при инициализации SDK.
/// Помеченный класс создаётся и ставится в <see cref="BackgroundTaskTracker"/> сам,
/// вручную вызывать <c>Register</c> не нужно.
/// </summary>
/// <remarks>
/// Требования к классу: наследник <see cref="BackgroundTask"/>, не абстрактный,
/// с публичным конструктором без параметров. Задачи, которым нужны параметры
/// конструктора или ссылка на объект сцены, регистрируйте вручную.
/// <para>
/// Атрибут не наследуется: производный класс не будет зарегистрирован автоматически,
/// пока не пометит себя сам. Иначе базовая задача и её наследник попали бы в реестр оба.
/// </para>
/// <para>
/// Задача создаётся рефлексией, и сборщик билда счёл бы её неиспользуемой. Помечать её
/// <c>[Preserve]</c> вручную не нужно: перед сборкой список помеченных типов попадает
/// в <c>link.xml</c> автоматически.
/// </para>
/// </remarks>
[AttributeUsage(AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
public sealed class AutoBackgroundTaskAttribute : Attribute
{
    /// <summary>
    /// Порядок регистрации: меньшее значение регистрируется раньше.
    /// Влияет только на порядок обхода в трекере, но не на расписание.
    /// </summary>
    public int Order { get; }

    /// <summary>
    /// Позволяет временно отключить автоматическую регистрацию, не убирая атрибут
    /// и не удаляя класс.
    /// </summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// Конструктор.
    /// </summary>
    /// <param name="order">Порядок регистрации.</param>
    public AutoBackgroundTaskAttribute(int order = 0)
    {
        Order = order;
    }
}
