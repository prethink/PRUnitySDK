/// <summary>
/// Итог обработки hook-контекста. Более высокое значение имеет больший приоритет
/// и не может быть перезаписано результатом с меньшим приоритетом.
/// </summary>
public enum HookResult
{
    /// <summary>
    /// Listener не повлиял на вызов. Оригинальное действие и его результат сохраняются.
    /// </summary>
    Ignored = 0,

    /// <summary>
    /// Listener обработал или изменил контекст, но оригинальное действие выполняется как обычно.
    /// </summary>
    Handled = 1,

    /// <summary>
    /// Оригинальное действие выполняется, однако итоговый результат предоставляет hook-контекст.
    /// </summary>
    Override = 2,

    /// <summary>
    /// Оригинальное действие не выполняется; итоговый результат предоставляет hook-контекст.
    /// Остальные listeners продолжают выполняться, пока явно не вызван StopPropagation().
    /// </summary>
    Supercede = 3
}
