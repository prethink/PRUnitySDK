/// <summary>
/// Что сейчас с логической жизнью сущности.
/// </summary>
/// <remarks>
/// Жизнь — это время, пока сущность участвует в игре. Она не совпадает ни со сроком объекта Unity
/// (один объект проживает много жизней: пул, спрятать и вернуть), ни со сроком записи экземпляра
/// (<see cref="EntityInstanceData"/> переживает сущность и переходит к другой).
/// <para>
/// Переходы:
/// <c>Created → Active</c> — первое появление (<c>Awake</c>);
/// <c>Active → Hidden | Pooled | Destroyed</c> — <c>DestroyEntity</c> по настройке сущности;
/// <c>Hidden → Active</c> — возврат спрятанных, запись экземпляра прежняя;
/// <c>Pooled → Active</c> — выдача из пула, запись экземпляра новая;
/// <c>Hidden | Pooled → Destroyed</c> — полное уничтожение, уже без события;
/// любое → <c>Destroyed</c> — объект уничтожила Unity (выгрузка сцены, очистка пула).
/// Из <c>Destroyed</c> выхода нет.
/// </para>
/// </remarks>
public enum EntityLifeState
{
    /// <summary>
    /// Компонент есть, жизнь ещё не началась: объект создан выключенным и <c>Awake</c> не прошёл.
    /// </summary>
    Created,

    /// <summary>
    /// Сущность живёт. Это не «жива» в смысле здоровья: убитый враг, который ещё лежит на сцене, тоже здесь.
    /// </summary>
    Active,

    /// <summary>
    /// Жизнь закончилась, объект спрятан на сцене и ждёт <c>EntityEvents.RestoreHideEntities</c>.
    /// </summary>
    Hidden,

    /// <summary>
    /// Жизнь закончилась, объект лежит в пуле и ждёт следующей выдачи.
    /// </summary>
    Pooled,

    /// <summary>
    /// Объект уничтожен или ждёт уничтожения до конца кадра. Конечное состояние.
    /// </summary>
    Destroyed,
}
