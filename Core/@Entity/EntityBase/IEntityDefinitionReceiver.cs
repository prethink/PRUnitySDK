/// <summary>
/// Сущность, которой определение можно выдать во время игры, а не только в префабе.
/// </summary>
/// <remarks>
/// Нужен там, где один префаб обслуживает несколько предметов: шлейфы эффектов, например,
/// различаются только правками поверх общего префаба, и записать определение в сам префаб
/// нельзя — оно там одно на все варианты.
/// <para>
/// Без этого сущность остаётся без <c>Info</c>: в отладчике у неё нет ни имени, ни иконки,
/// а код, который смотрит на <c>Info</c>, не отличит один вариант от другого.
/// </para>
/// </remarks>
public interface IEntityDefinitionReceiver
{
    /// <summary>
    /// Выдаёт сущности определение.
    /// </summary>
    /// <param name="definition">Определение предмета.</param>
    /// <returns>
    /// <see langword="false"/>, если определение не того типа — сущность остаётся как была.
    /// </returns>
    bool TryAssignDefinition(IEntityInfo definition);
}
