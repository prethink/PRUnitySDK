/// <summary>
/// Способ применения модификатора к базовому значению характеристики.
/// </summary>
/// <remarks>
/// Сериализуется на префабах и в определениях предметов: порядок и имена значений
/// менять нельзя без миграции существующих ассетов.
/// </remarks>
public enum StatModifierType
{
    /// <summary>Прибавляется к базовому значению.</summary>
    Add,

    /// <summary>Умножает значение после всех прибавлений.</summary>
    Multiply,

    /// <summary>Заменяет значение; сильнее тот, у кого выше приоритет.</summary>
    Override
}
