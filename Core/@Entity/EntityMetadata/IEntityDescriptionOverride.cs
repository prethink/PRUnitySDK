/// <summary>
/// Компонент, который переопределяет часть описания сущности.
/// </summary>
/// <remarks>
/// Каждый отвечает за одно: иконку, служебное имя, подпись. Так экземпляр на сцене меняет
/// ровно то, что нужно, не заводя отдельный ассет описания и не подменяя описание целиком
/// через <see cref="IEntityMetadataProvider"/>.
/// <para>
/// Компоненты собирает сама сущность при инициализации, поэтому переопределение действует
/// с первого обращения к описанию.
/// </para>
/// </remarks>
public interface IEntityDescriptionOverride
{
    /// <summary>
    /// Записывает своё переопределение в описание.
    /// </summary>
    /// <param name="description">Описание сущности.</param>
    void Apply(EntityDescription description);
}
