using UnityEngine;

/// <summary>
/// Какого размера каркас, который остаётся на месте спрятанной сущности.
/// </summary>
/// <remarks>
/// Сериализуется в настройках: порядок значений менять нельзя.
/// </remarks>
public enum EntityWireScaleMode
{
    /// <summary>
    /// Размер, с которым сущность появилась: у блока из префаба — размер префаба.
    /// </summary>
    [InspectorName("Исходный")] Original,

    /// <summary>
    /// Размер в момент смерти, вместе с тем, что на него повлияло: эффект попадания, зелье.
    /// </summary>
    [InspectorName("В момент смерти")] AtDeath
}
