/// <summary>
/// Состояние последней операции сохранения в текущей игровой сессии.
/// </summary>
public enum GameSaveState
{
    /// <summary>
    /// Сохранение ещё не запускалось.
    /// </summary>
    NotStarted,

    /// <summary>
    /// Хотя бы одна операция сохранения выполняется сейчас.
    /// </summary>
    Saving,

    /// <summary>
    /// Последняя завершённая операция сохранения прошла успешно.
    /// </summary>
    Succeeded,

    /// <summary>
    /// Последняя завершённая операция сохранения закончилась исключением.
    /// </summary>
    Failed
}
