using System;

/// <summary>
/// Помечает систему, которая сама сообщает реестру, какие предметы она выдаёт.
/// </summary>
/// <remarks>
/// Помеченный класс создаётся и регистрируется при инициализации SDK — вызывать
/// <c>Register</c> вручную не нужно. Так модуль остаётся самодостаточным: он объявляет
/// себя источником прямо там, где живёт, и не тянет за собой правку контейнера менеджеров.
/// <para>
/// Требования к классу: реализует <see cref="IReservedItemsProvider"/>, не абстрактный,
/// с публичным конструктором без параметров. Провайдеру, которому нужны аргументы или
/// ссылка на объект сцены, место в ручной регистрации.
/// </para>
/// <para>
/// Атрибут не наследуется: производный класс не попадёт в реестр, пока не пометит себя
/// сам — иначе базовый провайдер и его наследник дали бы два одинаковых ответа.
/// </para>
/// <para>
/// Класс создаётся рефлексией, и сборщик билда счёл бы его неиспользуемым. Помечать его
/// <c>[Preserve]</c> вручную не нужно: перед сборкой список помеченных типов попадает
/// в <c>link.xml</c> автоматически.
/// </para>
/// </remarks>
[AttributeUsage(AttributeTargets.Class, Inherited = false, AllowMultiple = false)]
public sealed class AutoReservedItemsProviderAttribute : Attribute
{
    /// <summary>
    /// Порядок регистрации: меньшее значение регистрируется раньше.
    /// </summary>
    /// <remarks>
    /// Важен только при совпадении предметов у двух систем: источником покажется та,
    /// что записалась позже.
    /// </remarks>
    public int Order { get; }

    /// <summary>
    /// Позволяет временно отключить автоматическую регистрацию, не убирая атрибут
    /// и не удаляя класс.
    /// </summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// Конструктор.
    /// </summary>
    /// <param name="order">Порядок регистрации.</param>
    public AutoReservedItemsProviderAttribute(int order = 0)
    {
        Order = order;
    }
}
