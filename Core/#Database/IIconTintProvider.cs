using UnityEngine;

/// <summary>
/// Определяет интерфейс для предметов, чья иконка красится в цвет предмета.
/// </summary>
/// <remarks>
/// Нужен там, где иконка одна на много вариантов: цвета тела, шлейфы, любые предметы,
/// отличающиеся только раскраской. Без покраски красный вариант в списке не отличить
/// от синего, а заводить отдельную картинку на каждый оттенок — лишняя работа.
/// <para>
/// Предмет может не иметь иконки вовсе: тогда цвет показывается сам по себе, и заливка
/// заменяет картинку.
/// </para>
/// </remarks>
public interface IIconTintProvider
{
    /// <summary>
    /// Цвет иконки.
    /// </summary>
    Color IconTint { get; }

    /// <summary>
    /// Красить иконку.
    /// </summary>
    /// <remarks>
    /// Отдельно от цвета, чтобы у предмета можно было хранить цвет и при этом показывать
    /// иконку как есть.
    /// </remarks>
    bool TintIcon { get; }
}
