/// <summary>
/// Элемент каталога, который делится на виды.
/// </summary>
/// <remarks>
/// Окно `Database` показывает по этому значению фильтр над сеткой. Нужен каталогам,
/// где лежат разнородные элементы: витрина, например, продаёт и шапки, и скины,
/// и пачки ресурсов, а искать среди них глазами неудобно.
/// <para>
/// Каталогам однородных предметов реализовывать нечего: там все элементы одного вида,
/// и фильтр не появится.
/// </para>
/// </remarks>
public interface IDatabaseCategoryProvider
{
    /// <summary>
    /// Вид элемента.
    /// </summary>
    string DatabaseCategory { get; }
}
