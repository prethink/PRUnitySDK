/// <summary>
/// Раздел настроек, который умеет вернуть себе значения по умолчанию.
/// </summary>
/// <remarks>
/// Метод с таким именем у разделов был и раньше — он вызывается при создании ассета
/// настроек. Интерфейс только делает его видимым снаружи: окно настроек спрашивает
/// им, есть ли у раздела собственное «по умолчанию», и зовёт именно его вместо того,
/// чтобы собирать раздел заново.
/// <para>
/// Разница заметна там, где значение по умолчанию не совпадает с инициализатором поля:
/// раздел, собранный заново, вернул бы инициализатор, а этот метод — то, что автор
/// раздела считает правильным стартом.
/// </para>
/// </remarks>
public interface IDefaultSettings
{
    /// <summary>
    /// Возвращает разделу значения по умолчанию.
    /// </summary>
    void SetDefaultSettings();
}
