using System;

/// <summary>
/// Слои времени: к каким группам относится объект и на какие группы действует замедление.
/// </summary>
/// <remarks>
/// Флаги, поэтому объект бывает в нескольких слоях сразу (враг — <see cref="Mobs"/> и <see cref="Enemy"/>), а
/// модификатор <see cref="PRTimeScale"/> задевает набор слоёв и может часть исключить: «всё, кроме игрока» — как
/// маска Кроноса в Crash Bandicoot 4. Объект попадает под модификатор, если у них есть хоть один общий слой.
/// <para>
/// <see cref="World"/> — темп мира: по нему идут шаг физики и <see cref="PRTime.GameDeltaTime"/>, в нём живёт
/// всё, у чего своего слоя нет. Тело в другом темпе догоняет или отстаёт от мира драйвером
/// (<see cref="RigidbodyTimeScaleDriverBase"/>): симуляция PhysX одна на сцену.
/// </para>
/// <para>
/// Группы — составные значения: <see cref="NPC"/> — это боты, питомцы и мобы разом. Модификатор на группу задевает
/// всех её участников, а на один слой — только его.
/// </para>
/// <para>
/// Новый слой добавляется следующим свободным битом. Значения существующих не менять: префабы хранят маску числом.
/// </para>
/// </remarks>
[Flags]
public enum TimeLayer
{
    None = 0,

    /// <summary>
    /// Мир: окружение, реквизит, всё без своего слоя. Задаёт шаг физики и <see cref="PRTime.GameDeltaTime"/>.
    /// </summary>
    World = 1 << 0,

    /// <summary>
    /// Игрок.
    /// </summary>
    Player = 1 << 1,

    /// <summary>
    /// Боты — соперники, играющие как игрок.
    /// </summary>
    Bots = 1 << 2,

    /// <summary>
    /// Питомцы.
    /// </summary>
    Pets = 1 << 3,

    /// <summary>
    /// Прочие персонажи игры: охрана, жители, монстры.
    /// </summary>
    Mobs = 1 << 4,

    /// <summary>
    /// Враги — те, от кого игрок спасается. Отдельно от того, кто это: враг-моб — <c>Mobs | Enemy</c>.
    /// </summary>
    Enemy = 1 << 5,

    /// <summary>
    /// Снаряды и всё летящее.
    /// </summary>
    Projectile = 1 << 6,

    /// <summary>
    /// Эффекты в мире: частицы, вспышки, твины на объектах сцены.
    /// </summary>
    Effects = 1 << 7,

    /// <summary>
    /// Интерфейс.
    /// </summary>
    UI = 1 << 8,

    /// <summary>
    /// Группа: все персонажи под управлением игры — боты, питомцы, мобы.
    /// </summary>
    NPC = Bots | Pets | Mobs,

    /// <summary>
    /// Все слои сразу, в том числе будущие: модификатор «на всё». «Всё, кроме игрока» — <c>Global</c> с
    /// исключением <see cref="Player"/>.
    /// </summary>
    Global = ~0,
}
