/// <summary>
/// Подписи разрядов для сокращённых чисел: K, M, B и далее.
/// </summary>
/// <remarks>
/// Отдельный поставщик, а не прямой вызов базы локализации: <see cref="NumberConverter"/>
/// живёт в ядре и вызывается в том числе до того, как переводы загрузились. Поставщика
/// ставит модуль локализации, а пока его нет, число выводится латинскими суффиксами.
/// <para>
/// Локализовать их нужно не ради красоты: в турецком <c>B</c> — это <c>bin</c>, тысяча,
/// а в английском — billion, то есть одна и та же буква означает разницу в миллион раз.
/// </para>
/// </remarks>
public interface INumberSuffixProvider
{
    /// <summary>
    /// Подпись разряда.
    /// </summary>
    /// <param name="power">
    /// Номер разряда: 0 — число без сокращения, 1 — тысячи, 2 — миллионы и так далее.
    /// </param>
    /// <returns>
    /// Подпись на текущем языке или <c>null</c>, если для этого разряда перевода нет —
    /// тогда берётся латинская.
    /// </returns>
    string GetSuffix(int power);
}
